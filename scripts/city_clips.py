"""Trajectory clips of representative city runs for the team site (task 5, card C5 bullet 3).

Reruns chosen runs of a city sweep exactly as scripts/city_sweep.py builds and runs them (its build() and
simulate(), so the same routes, seeds, controller and SUMO options), but ends each run at begin_s + length_s
and adds SUMO's FCD output from begin_s, so only the clip window is recorded (a whole run would be gigabytes).
It then checks each rerun against the sweep's own summary.xml up to that time (same cars running and halting
and the same mean speed at every step), and exports to [clips] out_dir:
  roads_<tag>.js     the road outlines once: every non-internal edge's lane-0 shape, in metres (net x, y)
  clip_<tag>_k<k>.js one file per density: the car IDs once, then one frame per step holding, per car in that
                     order, dx, dy: its position (net x, y, rounded to 1 m) minus its last known position,
                     starting from (0, 0), so the first frame holds absolute positions; null, null while a car
                     is missing (mid-teleport). Speeds are not stored: the viewer reads them from successive
                     positions (1 m per 1 s step = 3.6 km/h). Delta coding keeps the files small (docs/ is
                     published by GitHub Pages; the team README asks for compact exports there).

Run: python scripts/city_clips.py --config configs/city/bugis_all_clips.toml
"""
import argparse
import importlib.util
import json
import sys
import xml.etree.ElementTree as ET
from multiprocessing import Pool

from traffic_project import ROOT, config, demand, runner
from traffic_project.measurements import read_summary_xml

spec = importlib.util.spec_from_file_location("city_sweep", ROOT / "scripts" / "city_sweep.py")
cs = importlib.util.module_from_spec(spec)
sys.modules["city_sweep"] = cs   # so the worker pool can pickle cs.simulate by name
spec.loader.exec_module(cs)


def add_fcd(run_dir, begin_s):
    """Add FCD output from begin_s to the run's sumocfg (written by city_sweep.build)."""
    p = run_dir / "run.sumocfg"
    s = p.read_text()
    s = s.replace('<output><summary-output value="summary.xml"/></output>',
                  '<output><summary-output value="summary.xml"/><fcd-output value="fcd.xml"/>'
                  f'<device.fcd.begin value="{begin_s}"/></output>')
    assert "fcd-output" in s, "run.sumocfg changed shape: no <output> line to extend"
    p.write_text(s)


def check_rerun(run_dir, sweep_dir, end_s):
    """Largest difference between the rerun's and the sweep run's summary rows up to end_s."""
    a, b = read_summary_xml(run_dir / "summary.xml"), read_summary_xml(sweep_dir / "summary.xml")
    a = a[a[:, 0] <= end_s]
    b = b[b[:, 0] <= a[:, 0].max()]   # SUMO's last step is end_s - 1
    if len(a) != len(b):
        return dict(steps=len(a), sweep_steps=len(b), identical=False)
    d = abs(a - b).max(axis=0)
    return dict(steps=len(a), max_diff_running=float(d[1]), max_diff_halting=float(d[2]),
                max_diff_mean_speed_mps=float(d[3]), identical=bool((d == 0).all()))


def read_fcd(path, begin_s, end_s):
    """FCD file -> (times, {vehicle id: {time: (x, y, speed m/s)}})."""
    cars, times = {}, []
    for _, el in ET.iterparse(path):
        if el.tag != "timestep":
            continue
        t = float(el.get("time"))
        if begin_s <= t <= end_s:
            times.append(t)
            for v in el.iter("vehicle"):
                cars.setdefault(v.get("id"), {})[t] = (float(v.get("x")), float(v.get("y")), float(v.get("speed")))
        el.clear()
    return times, cars


def roads(net_path):
    """Every non-internal edge: id, lane count, speed limit and its lane-0 shape (rounded to 1 m)."""
    root = ET.parse(net_path).getroot()
    loc = root.find("location")
    out = []
    for e in root.iter("edge"):
        if e.get("function") == "internal":
            continue
        lanes = e.findall("lane")
        pts = [[round(float(c)) for c in xy.split(",")] for xy in lanes[0].get("shape").split()]
        out.append(dict(id=e.get("id"), lanes=len(lanes), speed_kmh=round(float(lanes[0].get("speed")) * 3.6),
                        shape=pts))
    return dict(boundary=[round(float(c)) for c in loc.get("convBoundary").split(",")], edges=out)


def js(var, key, obj, source):
    body = json.dumps(obj, separators=(",", ":"))
    return (f"// Generated by scripts/city_clips.py from {source}; do not edit.\n"
            f"window.{var} = window.{var} || {{}};\nwindow.{var}[\"{key}\"] = {body};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", required=True)
    a = ap.parse_args()
    ccfg = config.load(a.config)
    c = ccfg["clips"]
    cfg = config.load(ROOT / c["sweep_config"])
    end_s = c["begin_s"] + c["length_s"]
    cfg["run"]["end_s"] = end_s
    cfg["sweep"]["run_prefix"] = c["run_prefix"]
    overrides = {"end_s": end_s, "run_prefix": c["run_prefix"], "fcd_begin_s": c["begin_s"],
                 "clips_config": ccfg["_path"], "clips_config_sha256": ccfg["_sha256"]}
    cs.load_network(cfg)
    cs.CTX["near"] = demand.net_near_sets(cs.CTX["net_path"], cfg["controller"]["guard_m"])
    jobs, runs = [], {}
    for k in c["densities_veh_km"]:
        run_id, run_dir, n = cs.build(cfg, float(k), c["seed"], overrides)
        add_fcd(run_dir, c["begin_s"])
        runs[k] = (run_id, run_dir, n)
        jobs.append((run_id, run_dir, c["seed"], n, False))
    jobs.sort(key=lambda j: -j[3])
    print(f"{len(jobs)} clip runs to {end_s} s, FCD from {c['begin_s']} s, {c['jobs']} workers", flush=True)
    with Pool(min(c["jobs"], len(jobs)), initializer=cs._init_worker, initargs=(dict(cs.CTX),)) as pool:
        for run_id, rec in pool.imap_unordered(cs.simulate, jobs):
            print(f"{run_id:<30} N {rec['n_min']}-{rec['n_max']} (target {rec['n_vehicles']})  "
                  f"teleports {rec['teleports']}  wall {rec['wall_s']} s", flush=True)

    out = ROOT / c["out_dir"]
    out.mkdir(parents=True, exist_ok=True)
    tag = cfg["network"]["tag"]
    rd = roads(cs.CTX["net_path"])
    (out / f"roads_{tag}.js").write_text(js("NETWORK", f"roads_{tag}", dict(
        net=cfg["network"]["net_file"], units="m (net x, y); speed limit km/h", **rd), cfg["network"]["net_file"]))
    commit, version = runner.git_commit(), runner.sumo_version()
    for k, (run_id, run_dir, n) in runs.items():
        sweep_dir = ROOT / "runs" / f"{c['sweep_run_prefix']}_k{float(k):g}_s{c['seed']}"
        chk = check_rerun(run_dir, sweep_dir, end_s)
        times, cars = read_fcd(run_dir / "fcd.xml", c["begin_s"], end_s)
        ids = sorted(cars, key=lambda v: int(v[1:]) if v[1:].isdigit() else v)
        frames, last = [], {v: (0, 0) for v in ids}
        for t in times:
            f = []
            for v in ids:
                p = cars[v].get(t)
                if p is None:
                    f += [None, None]
                    continue
                x, y = round(p[0]), round(p[1])
                f += [x - last[v][0], y - last[v][1]]
                last[v] = (x, y)
            frames.append(f)
        missing = sum(1 for t in times for v in ids if t not in cars[v])
        meta = dict(scenario="city", net=tag, density_veh_km=float(k), seed=c["seed"], n_vehicles=n,
                    run_id=run_id, sweep_run_id=sweep_dir.name, rerun_check=chk, begin_s=times[0],
                    step_s=1, n_frames=len(times), units="dx, dy in m: position (net x, y, rounded to 1 m) minus the last known position, from (0, 0)",
                    config=c["sweep_config"], clips_config=ccfg["_path"], config_sha256=cfg["_sha256"],
                    git_commit=commit, sumo_version=version, car_ids=ids, frames=frames)
        path = out / f"clip_{tag}_k{float(k):g}.js"
        path.write_text(js("CLIPS", f"{tag}_k{float(k):g}", meta, f"runs/{run_id}/fcd.xml"))
        print(f"{path.relative_to(ROOT)}: {len(ids)} cars, {len(times)} frames ({times[0]:g}-{times[-1]:g} s), "
              f"{missing} car-frames missing (mid-teleport), {path.stat().st_size / 1e6:.2f} MB; rerun against "
              f"{sweep_dir.name}: {chk}", flush=True)


if __name__ == "__main__":
    main()
