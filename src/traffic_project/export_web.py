"""Export one experiment's validated results to the website.

Reads results/<scenario>/<name>.csv and the run records in runs/<run_id>/manifest.json,
and writes docs/data/<page>/<name>.js, which the page loads with a <script> tag:

    window.RESULTS["<page>/<name>"] = {
        scenario, page, name, model, config, config_sha256, sumo_version, git_commit, draft,
        columns: [...], units: {...}, rows: [[...], ...], excluded_invalid: <count>
    }

<page> is the site page that shows the results (GUIDE section 6, "Website files"): ring runs go
to ring, city runs to network, and planning variants (a config with [network] variant) to
planning; any other scenario keeps its own name. page= overrides it. Numbers keep 6 significant
digits, True and False become true and false, an empty cell or NaN becomes null, and any other
text stays text; run_id, model and variant stay as written.

Only valid runs are exported. The export stops with an error when
  - a run record is missing (runs/ is not in git, so export on the computer that ran it),
  - the config file changed after the runs (its hash differs from the run records),
  - the runs do not share one config hash, SUMO version and git commit (rerun the sweep),
  - the runs came from uncommitted code (git commit ending in -dirty), unless
    allow_dirty is set; the file is then marked draft: true.
The output has no timestamp, so exporting the same results twice gives the same file.
"""
import json

from . import ROOT, results
from .io import read_csv

# Columns not repeated in every row: the same for all exported runs, or always True
_DROP = {"scenario", "valid"}
_TEXT = {"run_id", "model", "variant"}
# Site page of each scenario, where the two names differ (docs/lab/<page>.html)
PAGES = {"city": "network"}


def page_of(cfg):
    """The site page whose folder docs/data/<page>/ receives cfg's results."""
    if cfg.get("network", {}).get("variant"):
        return "planning"
    return PAGES.get(cfg["scenario"], cfg["scenario"])


def _number(x):
    """Parse a CSV number, keeping 6 significant digits so the file stays small."""
    v = float(x)
    if v.is_integer() and abs(v) < 2 ** 53:
        return int(v)
    return float(f"{v:.6g}")


def _value(x):
    """A CSV cell for the site: a number, true/false, null for an empty cell or NaN, else text."""
    if x in ("True", "False"):
        return x == "True"
    if x == "":
        return None
    try:
        v = _number(x)
    except ValueError:
        return x
    return None if v != v else v   # NaN -> null


def _one(values, what):
    values = sorted(set(values))
    if len(values) != 1:
        raise ValueError(f"runs differ in {what}: {', '.join(values)}; rerun the whole sweep")
    return values[0]


def export(cfg, allow_dirty=False, page=None):
    """Write docs/data/<page>/<name>.js for the experiment in cfg; return its path."""
    scenario, name = cfg["scenario"], cfg["name"]
    page = page or page_of(cfg)
    table = ROOT / "results" / scenario / f"{name}.csv"
    rows = read_csv(table)
    valid = [r for r in rows if r["valid"] == "True"]
    if not valid:
        raise ValueError(f"{table.relative_to(ROOT)} has no valid runs to export")

    manifests = []
    for r in valid:
        path = ROOT / "runs" / r["run_id"] / "manifest.json"
        if not path.exists():
            raise ValueError(f"missing run record {path.relative_to(ROOT)}; "
                             "export on the computer that ran the sweep")
        manifests.append(json.loads(path.read_text()))

    config_sha = _one([m["config_sha256"] for m in manifests], "config hash")
    if config_sha != cfg["_sha256"]:
        raise ValueError(f"{cfg['_path']} changed after the runs "
                         f"(runs {config_sha}, file now {cfg['_sha256']}); rerun the sweep")
    sumo_version = _one([m["sumo_version"] for m in manifests], "SUMO version")
    git_commit = _one([m["git_commit"] for m in manifests], "git commit")
    draft = git_commit.endswith("-dirty")
    if draft and not allow_dirty:
        raise ValueError(f"the runs came from uncommitted code ({git_commit}); commit, rerun "
                         "the sweep and export again, or pass --allow-dirty for a draft")

    columns = [c for c in rows[0] if c not in _DROP]
    data = {
        "scenario": scenario,
        "page": page,
        "name": name,
        "model": cfg["model"],
        "config": cfg["_path"],
        "config_sha256": config_sha,
        "sumo_version": sumo_version,
        "git_commit": git_commit,
        "draft": draft,
        "columns": columns,
        "units": {n: u for n, u, _ in results.SUMMARY if n in columns and u},
        "rows": [[r[c] if c in _TEXT else _value(r[c]) for c in columns] for r in valid],
        "excluded_invalid": len(rows) - len(valid),
    }
    out = ROOT / "docs" / "data" / page / f"{name}.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"// Generated by scripts/export_web.py from results/{scenario}/{name}.csv; do not edit.\n"
        "window.RESULTS = window.RESULTS || {};\n"
        f'window.RESULTS["{page}/{name}"] = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n')
    return out
